import {readFile,writeFile} from "node:fs/promises";
import {createHash} from "node:crypto";
const root=new URL("../lib/catalog/",import.meta.url);
const [raw,schemas]=await Promise.all([readFile(new URL("metadata.json",root),"utf8"),readFile(new URL("schemas.json",root),"utf8").then(JSON.parse)]);
const models=JSON.parse(raw),ids=new Set();
if(!Array.isArray(models)||!models.length)throw new Error("The verified model catalog is empty.");
for(const model of models){
 if(!model.id||ids.has(model.id))throw new Error("Missing or duplicate model ID: "+model.id);
 ids.add(model.id);
 const url=new URL(model.sourceUrl);
 if(url.protocol!=="https:"||!["docs.higgsfield.ai","open.higgsfield.ai"].includes(url.hostname))throw new Error("Model source must be an official documentation URL: "+model.id);
 if(!schemas[model.id])throw new Error("Missing official input schema: "+model.id);
 if(!["image","video","audio"].includes(model.surface)||!Array.isArray(model.roles)||!Array.isArray(model.settings))throw new Error("Invalid model controls: "+model.id);
 for(const setting of model.settings)if(!["enum","range","boolean","text"].includes(setting.kind))throw new Error("Unsupported setting type: "+model.id+"/"+setting.key);
}
const hash=createHash("sha256").update(raw).digest("hex");
const output=`// Generated by pnpm models from the reviewed official-schema snapshot. Do not edit.\n// metadata.json SHA-256: ${hash}\nimport type {ModelEntry} from "./types";\nconst models:readonly ModelEntry[]=${JSON.stringify(models,null,2)};\nexport default models;\n`;
const target=new URL("models.generated.ts",root);
if(process.argv.includes("--check")){
 let existing="";try{existing=await readFile(target,"utf8");}catch{}
 if(existing!==output)throw new Error("Model output is stale. Run pnpm models and commit the generated file.");
 console.log(`Verified ${models.length} generated models against the reviewed snapshot.`);
}else{await writeFile(target,output);console.log(`Generated ${models.length} typed models; metadata SHA-256 ${hash}.`);}
