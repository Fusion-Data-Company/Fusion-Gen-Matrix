import {chromium} from "@playwright/test";
import fs from "node:fs/promises";
const base=process.env.BASE_URL||"http://127.0.0.1:3210";
const folder="docs/evidence";
await fs.mkdir(folder,{recursive:true});
const browser=await chromium.launch({channel:"chrome",headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const page=await context.newPage(),errors=[];
page.on("pageerror",error=>errors.push(error.message));
await page.goto(base,{waitUntil:"networkidle"});
await page.screenshot({path:folder+"/explore-desktop.png",fullPage:true});
console.log("TITLE",await page.title());
console.log("BUTTONS",await page.getByRole("button").allTextContents());
console.log("BODY", (await page.locator("body").innerText()).slice(0,1000));
await page.goto(base+"/image",{waitUntil:"networkidle"});
await page.screenshot({path:folder+"/image-desktop.png",fullPage:true});
console.log("IMAGE_BUTTONS",await page.getByRole("button").allTextContents());
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:folder+"/image-mobile.png",fullPage:true});
console.log("MOBILE_OVERFLOW",await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth})));
console.log("PAGE_ERRORS",errors);
await browser.close();
